import React from 'react';
import { Check, ClipboardList, Clock, User, Hash } from "lucide-react";

function PatientTokenSuccess({ tokenNumber = 4, patientData, successData, onReset, ...props }) {
    // Format current time or use API time
    // Format current time or use API time
    const formatTime = (timeVal) => {
        if (!timeVal) return new Date().toLocaleTimeString('en-US', {
            hour: 'numeric',
            minute: '2-digit',
            hour12: true
        });

        // Try parsing as date
        const date = new Date(timeVal);
        if (!isNaN(date.getTime()) && (timeVal.includes('T') || timeVal.includes('-'))) {
            return date.toLocaleTimeString('en-US', {
                hour: 'numeric',
                minute: '2-digit',
                hour12: true
            });
        }
        return timeVal;
    };

    const displayTime = formatTime(successData?.["Time"]);

    const displayDate = successData?.["Date"] || new Date().toLocaleDateString();

    return (
        <div className="max-w-xl mx-auto animate-in fade-in slide-in-from-bottom-4 duration-500">
            <div className="bg-white rounded-3xl shadow-sm border border-gray-100 overflow-hidden text-center pb-8">

                {/* Success Header */}
                <div className="pt-8 pb-5 px-8">
                    <div className="w-18 h-18 bg-green-100 rounded-full flex items-center justify-center mx-auto mb-2 animate-in zoom-in duration-300 delay-150">
                        <Check size={30} className="text-green-500" strokeWidth={3} />
                    </div>
                    <h2 className="text-2xl font-bold text-slate-900 ">Token Generated!</h2>
                    <p className="text-gray-500">The patient has been added to today's queue</p>
                </div>

                <div className='flex flex-col items-center justify-center w-full' >
                    {/* Token Display */}
                    <div className="p-7 bg-teal-100 rounded-2xl border border-teal-100">
                        <p className="text-sm font-medium text-teal-600 mb-1 uppercase tracking-wide">Token Number</p>
                        <div className="text-6xl font-black text-teal-600 tracking-tight">{tokenNumber}</div>
                    </div>
                </div>

                {/* Info Grid */}
                <div className="mx-8 my-7  bg-gray-100 rounded-2xl p-6 space-y-4">
                    <div className="flex items-center justify-between">
                        <span className="text-gray-500 text-sm font-medium flex items-center gap-2">
                            <User size={16} />
                            Patient
                        </span>
                        <span className="text-slate-900 font-bold text-sm">{patientData?.fullName || patientData?.name || successData?.["Patient Name"] || 'Unknown'}</span>
                    </div>

                    <div className="flex items-center justify-between">
                        <span className="text-gray-500 text-sm font-medium flex items-center gap-2">
                            <Hash size={16} />
                            Patient ID
                        </span>
                        <span className="bg-orange-50 text-orange-700 px-2 py-1 rounded text-xs font-bold border border-orange-100">
                            {successData?.["Patient ID"] || `# SHF-${new Date().getFullYear()}-XXXX`}
                        </span>
                    </div>

                    <div className="flex items-center justify-between">
                        <span className="text-gray-500 text-sm font-medium flex items-center gap-2">
                            <User size={16} />
                            Generated By
                        </span>
                        <span className="text-slate-900 text-sm font-medium">{successData?.["Generated By"] || 'System'}</span>
                    </div>

                    <div className="flex items-center justify-between">
                        <span className="text-gray-500 text-sm font-medium flex items-center gap-2">
                            <Clock size={16} />
                            Time
                        </span>
                        <span className="text-slate-900 text-sm font-medium">{displayTime}</span>
                    </div>
                </div>

                {/* Action Button */}
                <div className="px-8">
                    <button
                        onClick={onReset}
                        className="w-full py-3 bg-[#14B8A6] hover:bg-teal-600 text-white font-medium text-sm rounded-xl shadow-teal-900/20 transition-all duration-200 active:scale-[0.98]"
                    >
                        {props.actionLabel || "Register Next Patient"}
                    </button>
                </div>

            </div>
        </div>
    );
}

export default PatientTokenSuccess;